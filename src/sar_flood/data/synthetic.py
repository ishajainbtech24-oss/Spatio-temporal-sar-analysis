"""Synthetic Sen1Floods11-format data for tests, CI and smoke runs.

The generated chips mimic the *format* of Sen1Floods11 (2-band float32 dB GeoTIFFs with
NaN no-data, int16 labels with -1/0/1, official-style split CSVs) and the basic physics
(open water = low, smooth backscatter; land = brighter, speckled). They are NOT real
Sentinel-1 data and any metric computed on them says nothing about real-world skill.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
from scipy.ndimage import gaussian_filter

from .sen1floods11 import LABEL_SUBDIR, S1_SUBDIR, SPLIT_FILES

EVENTS = ["Alpha", "Bravo", "Charlie", "Delta", "Echo", "Foxtrot"]


def _water_mask(rng: np.random.Generator, size: int) -> np.ndarray:
    field_ = gaussian_filter(rng.normal(size=(size, size)), sigma=size / 10)
    thresh = np.quantile(field_, rng.uniform(0.45, 0.85))
    water = field_ > thresh
    # a "river" through some chips
    if rng.random() < 0.5:
        yy, xx = np.mgrid[0:size, 0:size]
        c = rng.uniform(0.2, 0.8) * size + 0.15 * size * np.sin(xx / size * rng.uniform(2, 6))
        water |= np.abs(yy - c) < size * 0.04
    return water


def make_chip(rng: np.random.Generator, size: int = 128, nodata: bool = False):
    """Return ``(image[2,H,W] float32 dB, label[H,W] int16)``."""
    water = _water_mask(rng, size)
    look = rng.gamma(shape=4.0, scale=1 / 4.0, size=(2, size, size))  # 4-look speckle
    vv_lin = np.where(water, 10 ** (-21 / 10), 10 ** (rng.uniform(-11, -7) / 10)) * look[0]
    vh_lin = np.where(water, 10 ** (-28 / 10), 10 ** (rng.uniform(-18, -14) / 10)) * look[1]
    image = (10 * np.log10(np.stack([vv_lin, vh_lin]))).astype(np.float32)
    label = water.astype(np.int16)
    if nodata:  # swath edge: a no-data wedge in image and label
        cut = int(size * rng.uniform(0.1, 0.3))
        image[:, :, :cut] = np.nan
        label[:, :cut] = -1
    # scattered unlabelled pixels, as in hand-labelled masks
    label[rng.random((size, size)) < 0.01] = -1
    return image, label


def write_dataset(root: str | Path, n_per_event: int = 4, size: int = 128, seed: int = 0) -> Path:
    """Write a synthetic dataset to ``root`` in the Sen1Floods11 folder layout."""
    import rasterio  # noqa: PLC0415
    from rasterio.transform import from_bounds  # noqa: PLC0415

    root = Path(root)
    (root / S1_SUBDIR).mkdir(parents=True, exist_ok=True)
    (root / LABEL_SUBDIR).mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed)
    ids_by_event: dict[str, list[str]] = {}
    for e_idx, event in enumerate(EVENTS):
        for i in range(n_per_event):
            chip_id = f"{event}_{1000 + i}"
            image, label = make_chip(rng, size=size, nodata=(i % 3 == 0))
            # ~10 m pixels somewhere on the equator, a different longitude per event
            west, south = 10.0 * e_idx + 0.05 * i, 0.0
            transform = from_bounds(west, south, west + size * 9e-5, south + size * 9e-5, size, size)
            common = {"driver": "GTiff", "height": size, "width": size,
                      "crs": "EPSG:4326", "transform": transform}
            with rasterio.open(root / S1_SUBDIR / f"{chip_id}_S1Hand.tif", "w", count=2,
                               dtype="float32", **common) as dst:
                dst.write(image)
            with rasterio.open(root / LABEL_SUBDIR / f"{chip_id}_LabelHand.tif", "w", count=1,
                               dtype="int16", **common) as dst:
                dst.write(label[None])
            ids_by_event.setdefault(event, []).append(chip_id)
    # official-style split files: events 0-3 train, 4 valid, 5 test
    split_dir = root / "splits" / "flood_handlabeled"
    split_dir.mkdir(parents=True, exist_ok=True)
    assignment = {"train": EVENTS[:4], "val": [EVENTS[4]], "test": [EVENTS[5]]}
    for split, events in assignment.items():
        with (split_dir / SPLIT_FILES[split]).open("w", encoding="utf-8") as fh:
            for ev in events:
                for cid in ids_by_event[ev]:
                    fh.write(f"{cid}_S1Hand.tif,{cid}_LabelHand.tif\n")
    (root / "SYNTHETIC_DATA_README.txt").write_text(
        "Synthetic data generated by sar_flood.data.synthetic. Not real Sentinel-1 imagery.\n",
        encoding="utf-8",
    )
    return root
